/**
 * Generated files that are no longer produced must not linger — but the
 * cleanup may only touch files this generator wrote. Ownership is decided by
 * the banner, not by "it has the right extension and I don't recognize it":
 * the slice directories also hold hand-written files (tests, a tsconfig), and
 * an over-broad rule here deletes them.
 */
function staleFiles(expected) {
  const marker = BANNER.split("\n")[0];
  const stale = [];
  for (const dir of ["dart/lib", "ts"]) {
    const abs = path.join(outDir, dir);
    if (!fs.existsSync(abs)) continue;
    for (const name of fs.readdirSync(abs)) {
      const rel = `${dir}/${name}`;
      const full = path.join(abs, name);
      if (fs.statSync(full).isDirectory()) continue;
      if (!/\.(dart|ts)$/.test(name)) continue;
      if (rel in expected) continue;
      const head = fs.readFileSync(full, "utf8").slice(0, 200);
      if (head.includes(marker)) stale.push(rel);
    }
  }
  return stale;
}

function main() {
  const check = process.argv.includes("--check");
  let files;
  try {
    files = build();
  } catch (error) {
    console.error(`error: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(2);
  }

  let drift = 0;
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(outDir, rel);
    if (check) {
      const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
      if (current !== content) {
        console.error(`drift: src/${rel}`);
        if (process.env.GITHUB_ACTIONS === "true") {
          console.error(`::error file=src/${rel}::generated slice is out of date; run \`npm run codegen\``);
        }
        drift += 1;
      }
    } else {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, content);
      console.log(`wrote src/${rel}`);
    }
  }

  for (const rel of staleFiles(files)) {
    if (check) {
      console.error(`stale: src/${rel} is no longer generated`);
      drift += 1;
    } else {
      fs.rmSync(path.join(outDir, rel));
      console.log(`removed src/${rel}`);
    }
  }

  if (check && drift > 0) {
    console.error(`${drift} file(s) out of date — run: npm run codegen`);
    process.exit(1);
  }
  if (check) console.log(`generated slices up to date (${Object.keys(files).length} files)`);
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) main();
